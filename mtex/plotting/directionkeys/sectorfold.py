def _angle(u, v):
  u, v = np.asarray(u, dtype=float), np.asarray(v, dtype=float)
  return np.arctan2(np.linalg.norm(np.cross(u, v), axis=-1), np.sum(u * v, axis=-1))


def uniqueNormals(sR):
  """the distinct boundary normals of a spherical region, repeated ones dropped"""
  N = []
  for n in sR.N:
    if not any(m @ n > 1 - 1e-9 for m in N):
      N.append(n)
  return N


def regionCenter(sR, resolution=1 * degree):
  """the centre of a region (MATLAB @sphericalRegion/center): the pole of a single circle, the
  bisector of the two boundaries furthest apart for a lune, the barycentre of the vertices
  of a triangle, and the area centroid of anything larger. The fold is a symmetry of the
  sector, so it is this centre and not the group's Dirichlet centre that it turns about

    c = regionCenter(cs.fundamentalSector())                         # the centre as an (3,) array
    c = regionCenter(cs.fundamentalSector(), resolution=0.5*degree)  # a finer grid for the centroid

  The resolution matters only for a region of four or more vertices, whose centroid is
  summed over an equispaced grid of that spacing; a region without boundary has its centre
  at z.

  Input
    sR - sphericalRegion
  Output
    c - (3,) array, the unit vector of the centre
  Keywords
    resolution - the spacing of the grid the area centroid is summed over
  See also
    sphericalRegion.center, polarCoordinates, sectorFolds"""
  return sR.center(resolution).data.reshape(3)


def foldsSector(n, sR, tol=1e-6):
  """the reflection in a plane is a symmetry of the sector when it maps its boundary planes
  onto themselves"""
  n = unitRows(n)
  N = uniqueNormals(sR)
  return all(any((m - 2 * (m @ n) * n) @ k > 1 - tol for k in N) for m in N)


def foldCandidates(sR, center):
  """the candidate mirrors of a sector: a reflection symmetry of a spherical polygon runs
  through two of its characteristic points, its vertices, the middles of its edges, the
  poles of its boundaries and its centre, so every plane through two of them is tried"""
  P = [unitRows(center)] + [unitRows(n) for n in uniqueNormals(sR)] + [np.eye(3)[k] for k in range(3)]
  V = list(sR.vertices().data.reshape(-1, 3))
  P += V
  for i in range(len(V)):
    for j in range(i + 1, len(V)):
      w = V[i] + V[j]
      if np.linalg.norm(w) > 1e-9:
        P.append(unitRows(w))
  N = []
  for i in range(len(P)):
    for j in range(i + 1, len(P)):
      w = np.cross(P[i], P[j])
      if np.linalg.norm(w) < 1e-8:
        continue
      n = unitRows(w)
      if not any(abs(m @ n) > 1 - 1e-9 for m in N):
        N.append(n)
  return N


def finiteClosure(els, extra):
  """the closure, or None where the generators build no finite group"""
  try:
    return closure(orthogonalTransform.cat(els, extra))
  except ValueError:
    return None


def isReflectionGroup(els):
  """a group generated by its own mirrors: the reflection groups are the ones whose sector is
  bounded by mirrors, and colouring asks for nothing else"""
  mirrors = els[els.isImproper & (np.abs(els.angle() - np.pi) < 1e-6)]
  return mirrors.size > 0 and closure(mirrors).size == els.size


def _isMirror(n, els):
  return bool(_isin(reflection(vector3d(n)), els)[0])


def orientFold(n, pg):
  """which half of the sector a fold keeps is a convention, both halves being fundamental
  domains of the reflection group: MTEX keeps the half the frame's east lies in, and where
  east lies in the plane itself the north and then the pole decide"""
  for d in (np.asarray(pg.axes[k], dtype=float) for k in range(3)):
    x = n @ unitRows(d)
    if abs(x) > 1e-6:
      return n if x > 0 else -n
  return n


def sectorFolds(pg, sR=None, tol=1e-6):
  """the folds of a group's sector, in the order they are applied. Every fold halves the
  sector and flips the half between the white centre and the black one; the loop stops when
  every boundary plane is a mirror of the group the folds have generated. The groups -1, -3
  and -4 have no such fold and no smooth one to one key; hasSmoothKey says so. -3 and -4 fold
  their wedge once all the same; the hemisphere of -1 has no plane to single out and stays
  whole, white at its pole, as MATLAB's key

    folds = sectorFolds(crystalFrame('432').sym)   # one fold: 432 halves its sector to that of m-3m
    folds = sectorFolds(crystalFrame('m-3m').sym)  # no fold: the sector is bounded by mirrors
    folds = sectorFolds(cs.sym, cs.fundamentalSector(), tol=1e-4)  # another sector, a looser test

  A candidate plane folds the sector when the reflection in it maps the boundary planes of
  the sector onto themselves, within tol, and it is taken when it doubles the group to a
  reflection group. Which half a fold keeps is a convention: the half the first axis of the
  frame not lying in the plane points into.

  Input
    pg - symmetry, the point group
    sR - sphericalRegion, the sector to fold; by default the group's conventional sector
  Output
    folds - list of (3,) arrays, the normals of the folding planes in the order they apply
  Keywords
    tol - the tolerance of the test whether a reflection maps the sector onto itself
  See also
    hasSmoothKey, regionCenter, HSVDirectionKey"""
  sR = conventionalSector(pg) if sR is None else sR
  # the whole sphere, the sector of the trivial group, has no boundary to read a fold off:
  # it folds at the equator of the plotting convention, the pole white and its antipode
  # black, which is the key of a pole figure over a specimen without symmetry
  if len(sR.N) == 0:
    return [_conventionOf(sR.frame).outOfScreen.data.reshape(3).copy()]
  els = pg.rot.flatten()
  region = sR
  folds = []
  fellBack = False
  while not all(_isMirror(n, els) for n in uniqueNormals(region)):
    n = None
    fallback = None
    for c in foldCandidates(region, regionCenter(region)):
      if _isMirror(c, els) or not foldsSector(c, region, tol):
        continue
      # it must halve the group, and of the planes that do, the one whose closure is a
      # reflection group is the fold: that is what separates the vertical mirror of 4 from
      # the equator, both of which halve the sector while only 4mm is generated by mirrors
      cl = finiteClosure(els, reflection(vector3d(c)))
      if cl is None or cl.size != 2 * els.size:
        continue
      if isReflectionGroup(cl):
        n = c
        break
      if fallback is None:
        fallback = c
    # a fold that reaches no reflection group needs a wedge to halve
    if n is None and len(uniqueNormals(region)) > 1:
      n, fellBack = fallback, True
    if n is None:
      break
    nd = orientFold(n, pg)
    folds.append(nd)
    els = closure(orthogonalTransform.cat(els, reflection(vector3d(nd))))
    region = sphericalRegion(np.concatenate([region.N, nd[None]]), np.concatenate([region.alpha, [0.0]]), region.frame)
    # a fold that reaches no reflection group is the best there is, and a second one would
    # not reach one either: -3 and -4 fold once and their colours still jump
    if fellBack:
      break
  return folds


def hasSmoothKey(pg, sR=None):
  """a group whose sector neither is bounded by its own mirrors nor folds onto such a half has
  no continuous one to one key; the colours jump somewhere on the sector

    hasSmoothKey(crystalFrame('m-3m').sym)   # True
    hasSmoothKey(crystalFrame('-3').sym)     # False: the colours of -3 jump

  Input
    pg - symmetry, the point group
  Output
    tf - bool, whether the boundary planes and the folds are all mirrors of the group the
        folds generate
  Keywords
    sR - sphericalRegion, the sector; by default the group's conventional sector
  See also
    sectorFolds, HSVDirectionKey"""
  sR = conventionalSector(pg) if sR is None else sR
  folds = sectorFolds(pg, sR)
  els = closure(orthogonalTransform.cat(pg.rot.flatten(), *[reflection(vector3d(n)) for n in folds])) if folds else pg.rot.flatten()
  return all(_isMirror(n, els) for n in uniqueNormals(sR) + folds)


# ------------------------------------------------------------------ polar coordinates of a region

def polarCoordinates(sR, v, center, ref=None, equalise=True):
  """polar coordinates of a region (MATLAB @sphericalRegion/polarCoordinates), which is what a
  colour key is built on: the radius is one at the centre and zero on the boundary, taken
  along the great circle through the centre, and the azimuth is measured about the centre
  from a reference direction and then equalised, so that a wide part of the sector takes as
  much of the turn as a narrow one and the vertices sit at equal angles

    r, rho = polarCoordinates(sR, h, regionCenter(sR))                  # the radius and the equalised azimuth
    r, rho = polarCoordinates(sR, h, regionCenter(sR), equalise=False)  # the plain azimuth about the centre
    r, rho = polarCoordinates(sR, h, regionCenter(sR), ref=xvector)     # the reference direction for rho = 0

  The azimuth starts at the pole of the plotting convention seen from the centre; only where
  the centre is that pole does the reference direction take over. A centre at a vertex or
  on the boundary of the region spreads the part of the turn the region covers over the
  whole turn.

  Input
    sR - sphericalRegion
    v - vector3d, the directions
    center - vector3d or (3,) array, the centre of the coordinates
  Output
    r - array, one at the centre and zero on the boundary
    rho - array, the azimuth about the centre in [0, 2 pi)
  Keywords
    ref - the direction rho = 0 points to where the centre is the pole; x by default
    equalise - reparametrise the azimuth by the distance to the boundary
  See also
    regionCenter, HSVDirectionKey, sectorFolds"""
  xyz = asVector3d(v).data.reshape(-1, 3)
  c = unitRows(asVector3d(center).data.reshape(3))
  ref = np.array([1.0, 0.0, 0.0]) if ref is None else asVector3d(ref).data.reshape(3)
  N = [unitRows(n) for n in sR.N]
  r = polarRadius(N, xyz, c)
  # rho = 0 is taken from the pole of the drawing, and only where the centre is that pole
  # does the reference direction take over
  pole = _conventionOf(sR.frame).outOfScreen.data.reshape(3)
  rx = tangentAt(c, ref) if _angle(c, pole) < 1e-8 else tangentAt(c, pole)
  rho = azimuthAbout(c, rx, xyz)
  if equalise and N:
    rho = equaliseAzimuth(sR, c, rx, rho)
  return r, rho


def polarRadius(N, xyz, c):
  """one over the geodesic through the centre: the boundary crossing of that circle sets the
  scale, so the radius is one at the centre and zero where the circle leaves the region"""
  from ..kernels import polarRadius as radiusKernel
  if not N or all(abs(n @ c) < 1e-10 for n in N):
    return _angle(c, xyz) / np.pi
  return radiusKernel(N, xyz, c)


def tangentAt(c, ref):
  """the component of a direction perpendicular to the centre, the reference for rho = 0"""
  t = ref - (ref @ c) * c
  return unitRows(t) if np.linalg.norm(t) > 1e-10 else vector3d(c).orth().data.reshape(3)


def azimuthAbout(c, rx, xyz):
  """the azimuth of directions about the centre, from the tangent rx"""
  ry = np.cross(c, rx)
  dv = xyz - c
  small = np.linalg.norm(dv, axis=-1) < 1e-12
  a = np.mod(np.arctan2(dv @ ry, dv @ rx), 2 * np.pi)
  return np.where(small, 0.0, a)


def equaliseAzimuth(sR, c, rx, rho, steps=1000):
  """the azimuth equalised by how far the boundary is: rho is reparametrised by the cumulative
  distance from the centre to the boundary, so that every part of the turn carries as much
  of the sector as any other, and a triangle's vertices land on 0, 2pi/3 and 4pi/3"""
  V = sR.vertices().data.reshape(-1, 3)
  # the centre in a vertex, or on the boundary: the turn is a fraction of the full one
  atVertex = [v for v in V if _angle(c, v) < 1e-8]
  if atVertex:
    alpha = innerAngle(sR, atVertex[0])
    return np.mod(rho, alpha) * 2 * np.pi / alpha
  if any(abs(n @ c) < 1e-10 for n in sR.N):
    return np.mod(rho, np.pi) * 2
  if len(V) == 0:
    return rho
  # the distance to the boundary as the azimuth turns, the vertices' azimuths knots of the grid
  at = np.mod(azimuthAbout(c, rx, V), 2 * np.pi)
  phi = np.unique(np.concatenate([np.linspace(0, 2 * np.pi, steps + 1), at]))
  n1 = unitRows(np.cross(rx, c))
  n = (rotation.byAxisAngle(vector3d(c), phi) * vector3d(n1)).data.reshape(-1, 3)
  omega = np.full(len(phi), np.pi)
  for m in sR.N:
    cr = np.cross(m, n)
    ncr = np.linalg.norm(cr, axis=-1)
    ok = ncr > 1e-12
    omega[ok] = np.minimum(omega[ok], _angle(cr[ok] / ncr[ok][:, None], c))
  # the turn's share of every interval between two knots, by the trapezoid rule
  seg = (omega[:-1] + omega[1:]) / 2 * np.diff(phi)
  # a triangle's three arcs each take a third of the turn, so its vertices are pinned: an
  # interval belongs to the arc of the vertices passed before it, counted modulo three, so the
  # arc over rho = 0 is one arc whether or not a vertex sits there
  if len(V) == 3:
    arc = np.cumsum(np.isin(phi[:-1], at)) % 3
    for k in range(3):
      w = np.sum(seg[arc == k])
      if w > 0:
        seg[arc == k] /= 3 * w
  cum = np.concatenate([[0.0], np.cumsum(seg)]) / np.sum(seg) * 2 * np.pi
  return np.interp(np.mod(rho, 2 * np.pi), phi, cum)


def innerAngle(sR, v):
  """the inner angle of the region at one of its vertices"""
  on = [n for n in sR.N if abs(n @ v) < 1e-8]
  return 2 * np.pi if len(on) < 2 else np.pi - _angle(on[0], on[1])


