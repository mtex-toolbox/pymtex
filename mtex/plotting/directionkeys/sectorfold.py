# the fundamental sector as a colour key sees it: its centre, its polar coordinates with an
# equalised azimuth, and its folds onto the half coloured from a white centre (MATLAB
# @sphericalRegion/center, polarCoordinates, HSVDirectionKey; docs/plans/plotting.md S3)
#
# The key is white at the centre of the sector and carries the primary colours at its
# vertices. That works as it stands only where every boundary of the sector is a mirror of
# the group, since only there does the colour meet its own mirror image across the edge.
# Elsewhere the sector is twice the sector of the smallest reflection group containing the
# group, and the mirror halving it folds the sector onto the half coloured from a white
# centre, the other half being coloured from a black one. The fold is derived, not
# tabulated: the halving planes through the characteristic points of the sector are tried,
# and the one whose closure with the group is a reflection group is the fold.
