# the definitions of Julia source files, read by Julia's own parser, one JSON object per line
#
#   julia scan_julia.jl <root> <file> ...       files relative to root, or absolute
#
# A function or method: {"kind": "method", "name", "qual" (the module it extends, Base for
# Base.:*), "type" (the first annotated argument's type, parameters stripped), "file", "line",
# "end", "calls", "refs", "doc"}; a type: {"kind": "type", "name", "super", "file", "line"}; an alias
# `const A{..} = B{..}`: {"kind": "alias", "name", "of"}; an export list: {"kind": "export",
# "names"}; a script (a test or a benchmark, the
# file as one unit): {"kind": "script", "file", "calls", "refs"}. calls are the names called,
# refs the names passed as values and not bound in the body. Code generated by @eval is not seen.

# ----
# names

# the name of a callee or a definition head: f, M.f, M.:*, f{T}
function nameOf(x)
  x isa Symbol && return string(x), ""
  x isa QuoteNode && return nameOf(x.value)
  if x isa Expr
    x.head === :. && length(x.args) == 2 && x.args[2] isa QuoteNode && return nameOf(x.args[2])[1], string(x.args[1])
    x.head === :curly && return nameOf(x.args[1])
  end
  nothing, ""
end

# the type name of an annotation, parameters and wrappers stripped: AbstractArray{<:Rotation} is Rotation
function typeName(t)
  t isa Symbol && return string(t)
  t isa Expr || return nothing
  t.head === :. && return nameOf(t)[1]
  t.head === :<: && length(t.args) == 1 && return typeName(t.args[1])
  if t.head === :curly
    outer = typeName(t.args[1])
    if outer in ("AbstractArray", "AbstractVector", "AbstractMatrix", "Array", "Vector", "Matrix", "Type") && length(t.args) >= 2
      return typeName(t.args[2])
    end
    return outer
  end
  nothing
end

# the call of a signature, under a return type and where clauses
function callOf(sig)
  while sig isa Expr && sig.head in (:where, :(::))
    sig = sig.args[1]
  end
  sig isa Expr && sig.head === :call ? sig : nothing
end

# the type of the first positional argument with an annotation
function firstType(call)
  for a in call.args[2:end]
    a isa Expr && a.head === :parameters && continue
    a isa Expr && a.head === :kw && (a = a.args[1])
    a isa Expr && a.head === :(::) && return typeName(a.args[end])
  end
  nothing
end

# ----
# the body of a definition

# the names a body calls, passes as values, and binds
function uses!(calls, refs, bound, x)
  x isa Expr || return
  if x.head === :call
    n = nameOf(x.args[1])[1]
    n === nothing || push!(calls, n)
    x.args[1] isa Symbol || uses!(calls, refs, bound, x.args[1])
    for a in x.args[2:end]
      a isa Symbol ? push!(refs, string(a)) : uses!(calls, refs, bound, a)
    end
    return
  end
  # broadcasting f.(x)
  if x.head === :. && length(x.args) == 2 && x.args[2] isa Expr && x.args[2].head === :tuple
    n = nameOf(x.args[1])[1]
    n === nothing || push!(calls, n)
    uses!(calls, refs, bound, x.args[2])
    return
  end
  x.head === :. && return uses!(calls, refs, bound, x.args[1])
  if x.head in (:(=), :local, :for, :->, :function, :kw) && !isempty(x.args)
    for s in lhsNames(x.args[1])
      push!(bound, s)
    end
  end
  for a in x.args
    uses!(calls, refs, bound, a)
  end
end

function lhsNames(x)
  x isa Symbol && return [string(x)]
  x isa Expr || return String[]
  x.head === :call && return reduce(vcat, lhsNames.(x.args[2:end]); init = String[])
  x.head in (:tuple, :parameters, :block) && return reduce(vcat, lhsNames.(x.args); init = String[])
  x.head in (:(::), :kw, :(=)) && return lhsNames(x.args[1])
  String[]
end

lastLine(x, l) = x isa LineNumberNode ? max(l, x.line) : x isa Expr ? foldl((m, a) -> lastLine(a, m), x.args; init = l) : l

# ----
# the walk over a file

function emit(io, d)
  print(io, "{", join(("\"$k\":" * (v isa AbstractString ? "\"" * escape_string(v) * "\"" : v isa Integer ? string(v) :
                       v === nothing ? "null" : "[" * join(("\"" * escape_string(s) * "\"" for s in v), ",") * "]") for (k, v) in d), ","), "}\n")
end

function definition!(io, file, line, sig, body, doc)
  call = callOf(sig)
  call === nothing && return
  name, qual = nameOf(call.args[1])
  name === nothing && return
  calls, refs, bound = Set{String}(), Set{String}(), Set{String}(lhsNames(call))
  uses!(calls, refs, bound, body)
  emit(io, ("kind" => "method", "name" => name, "qual" => qual, "type" => firstType(call), "file" => file, "line" => line,
            "end" => lastLine(body, line), "calls" => sort!(collect(calls)), "refs" => sort!(collect(setdiff(refs, bound))),
            "doc" => doc === nothing ? "" : first(doc, 2000)))
end

isDoc(x) = x isa Expr && x.head === :macrocall && (x.args[1] == GlobalRef(Core, Symbol("@doc")) || x.args[1] === Symbol("@doc"))
docString(x) = (k = findfirst(a -> a isa AbstractString, x.args); k === nothing ? nothing : x.args[k])

function walk!(io, file, x, line = 0, doc = nothing)
  x isa Expr || return
  # a docstring belongs to the definition it precedes
  isDoc(x) && (doc = docString(x))
  for a in (x.head in (:toplevel, :block, :module, :macrocall) ? x.args : Any[x])
    if a isa LineNumberNode
      line = a.line
    elseif a isa Expr && a.head in (:toplevel, :block, :macrocall)
      walk!(io, file, a, line, isDoc(x) ? doc : nothing)
    elseif a isa Expr && a.head === :module
      walk!(io, file, a.args[3], line)
    elseif a isa Expr && a.head === :function && length(a.args) == 2
      definition!(io, file, line, a.args[1], a.args[2], x.head === :macrocall ? doc : nothing)
    elseif a isa Expr && a.head === :(=) && callOf(a.args[1]) !== nothing
      definition!(io, file, line, a.args[1], a.args[2], x.head === :macrocall ? doc : nothing)
    elseif a isa Expr && a.head === :struct
      head = a.args[2]
      sup = head isa Expr && head.head === :<: ? typeName(head.args[2]) : nothing
      tname = typeName(head isa Expr && head.head === :<: ? head.args[1] : head)
      emit(io, ("kind" => "type", "name" => tname, "super" => sup, "file" => file, "line" => line))
      walk!(io, file, a.args[3], line)
    elseif a isa Expr && a.head === :export
      emit(io, ("kind" => "export", "file" => file, "names" => [string(n) for n in a.args if n isa Symbol]))
    elseif a isa Expr && a.head === :abstract
      head = a.args[1]
      sup = head isa Expr && head.head === :<: ? typeName(head.args[2]) : nothing
      emit(io, ("kind" => "type", "name" => typeName(head isa Expr && head.head === :<: ? head.args[1] : head), "super" => sup,
                "file" => file, "line" => line))
    elseif a isa Expr && a.head === :const && a.args[1] isa Expr && a.args[1].head === :(=)
      lhs, rhs = a.args[1].args
      t, of = typeName(lhs), typeName(rhs)
      t !== nothing && of !== nothing && isuppercase(first(t)) && isuppercase(first(of)) &&
        emit(io, ("kind" => "alias", "name" => t, "of" => of, "file" => file, "line" => line))
    end
  end
end

function scanFile(io, root, file)
  path = isabspath(file) ? file : joinpath(root, file)
  src = read(path, String)
  ex = try
    Meta.parseall(src; filename = path)
  catch
    return
  end
  if occursin(r"(^|/)(test|bench)/", file)
    calls, refs, bound = Set{String}(), Set{String}(), Set{String}()
    uses!(calls, refs, bound, ex)
    emit(io, ("kind" => "script", "file" => file, "calls" => sort!(collect(calls)), "refs" => sort!(collect(setdiff(refs, bound)))))
  else
    walk!(io, file, ex)
  end
end

let io = IOBuffer()
  for f in ARGS[2:end]
    scanFile(io, ARGS[1], f)
  end
  write(stdout, take!(io))
end
