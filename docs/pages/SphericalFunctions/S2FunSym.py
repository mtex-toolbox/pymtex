# ## Technical Details
#
# The port has no `S2FunHarmonicSym`: a frame carries its point group, so an
# `S2FunHarmonic` in a frame with symmetry is the symmetric function. MATLAB's two steps,
# `S2FunHarmonicSym(sF, ss)` attaching the frame and `symmetrise` averaging, are the one
# call `symmetrise(sF, ss)`, since a function whose frame claims a symmetry it does not have
# is not a state the port admits. MATLAB's `clf` before a plot has no counterpart; every
# plot opens its own figure.
#
# The sector of `222` holds a quarter of the sphere, the half $y \ge 0$ of a hemisphere. In
# MATLAB `symmetrise` returns a plain `S2FunHarmonic` again, and its plot shows the octant
# $x, y, z \ge 0$, half of that sector; the symmetrised smiley is not antipodal, so the
# octant does not show every value.
