# # MTEX release notes
#
# This page of the MATLAB documentation is MTEX's release history, newest first, from the
# current release back to the first. It records what changed in MTEX and is not transcribed
# here: read it in the MATLAB documentation,
# [MTEX release notes](https://mtex-toolbox.github.io/changelog.html), or in `CHANGELOG.md`
# in the MTEX folder, which holds the technical detail behind each change.
#
# The history of the Python port is its git log and its plans:
#
# * `docs/PLAN.md`, the plan of the port, its phases P1 to P8 and the cut of the package
#   into the cores `mtex.geometry`, `mtex.functions`, `mtex.tensors`, `mtex.maps` and the
#   algorithms of `mtex.analysis`;
# * `docs/plans/`, one subplan per phase (`geometry.md`, `functions.md`, `maps.md`,
#   `plotting.md`, `io.md`, `docs.md`, `wizard.md`), each with the status of its steps and
#   the date they were done;
# * `docs/plans/remaining-pages.md`, the state of every page of this documentation, and
#   `docs/findings.md`, what the pages found: the bugs, the gaps beside MTEX and the
#   conventions that differ from MATLAB.
#
# The port follows the syntax of MTEX's development branch, so a release note of MATLAB
# describes the port too once the feature it names is in the plans as done.
